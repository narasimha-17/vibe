"""Integration agent: wires the generated frontend and backend together and reports what it found.

It is deterministic (no model): it reads the generated files, lists every API call the frontend makes,
matches them against the routes the backend defines, aligns environment variables and CORS, and writes the
full-stack README plus an INTEGRATION_REPORT.md.
"""

import re
from dataclasses import dataclass, field

from app.codegen.engine import GenFile
from app.codegen import widgets


@dataclass
class Check:
    name: str
    status: str  # pass | fail | warn | info
    detail: str = ""


@dataclass
class IntegrationReport:
    checks: list[Check] = field(default_factory=list)
    actions: list[str] = field(default_factory=list)
    calls: list[str] = field(default_factory=list)
    routes: list[str] = field(default_factory=list)

    @property
    def ok(self) -> bool:
        return not any(c.status == "fail" for c in self.checks)

    def to_dict(self) -> dict:
        return {
            "ok": self.ok,
            "checks": [c.__dict__ for c in self.checks],
            "actions": self.actions,
            "calls": self.calls,
            "routes": self.routes,
        }


def _norm(path: str) -> str:
    path = re.sub(r"\$\{[^}]*\}", "{}", path)
    path = re.sub(r"\{[a-zA-Z_]+\}", "{}", path)
    return path.split("?")[0].rstrip("/") or "/"


FORM_ENDPOINTS = {"contact": "/api/contact", "booking": "/api/bookings", "subscription": "/api/subscribers"}


def frontend_calls(files: list[GenFile], project: dict | None = None) -> list[str]:
    """Endpoint paths the frontend requests (from the widget source files).

    The form widget carries all three form endpoints; only those for form kinds that are actually on the site count.
    """
    used_forms = {
        (n.get("variant") if n.get("variant") in FORM_ENDPOINTS else "contact")
        for pg in (project or {}).get("pages", [])
        for n in pg.get("tree", [])
        if n.get("type") == "forms"
    }
    skip = {path for kind, path in FORM_ENDPOINTS.items() if project is not None and kind not in used_forms}
    found: set[str] = set()
    for f in files:
        if "widgets/" not in f.path or not f.path.endswith(".tsx"):
            continue
        for m in re.finditer(r"`\$\{apiUrl\}(/api/[^`]*)`", f.content):
            found.add(_norm(m.group(1)))
        for m in re.finditer(r'"(/api/[a-z_/-]+)"', f.content):  # e.g. ENDPOINT map in FormWidget
            found.add(_norm(m.group(1)))
    return sorted(found - skip)


def backend_routes(files: list[GenFile]) -> list[str]:
    routes: set[str] = set()
    for f in files:
        if not f.path.startswith("backend/") or not f.path.endswith(".py"):
            continue
        prefix_match = re.search(r'APIRouter\(prefix="([^"]*)"', f.content)
        prefix = prefix_match.group(1) if prefix_match else ""
        for m in re.finditer(r'@router\.(?:get|post|put|patch|delete)\(\s*"([^"]*)"', f.content):
            routes.add(_norm(prefix + m.group(1)))
        # Flask / Django style
        for m in re.finditer(r'@api\.(?:get|post|put|patch|delete)\("([^"]*)"', f.content):
            routes.add(_norm("/api" + re.sub(r"<[a-z]+:[a-z_]+>", "{}", m.group(1))))
        for m in re.finditer(r'path\("([^"]+)"', f.content):
            routes.add(_norm("/api/" + re.sub(r"<[a-z]+:[a-z_]+>", "{}", m.group(1))))
    return sorted(routes)


def _has_backend(files: list[GenFile]) -> bool:
    return any(f.path.startswith("backend/") for f in files)


