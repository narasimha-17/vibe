def integrate(files: list[GenFile], project: dict, options) -> tuple[list[GenFile], IntegrationReport]:
    report = IntegrationReport()
    has_backend = _has_backend(files)
    framework = options.framework
    calls = frontend_calls(files, project)
    routes = backend_routes(files) if has_backend else []
    report.calls, report.routes = calls, routes
    by_path = {f.path: f for f in files}

    # 1. contract: every call the frontend makes must exist on the backend
    if calls and not has_backend:
        report.checks.append(Check("Frontend has a backend to talk to", "info", "Widgets run in preview mode because no backend was generated."))
    for call in calls:
        matched = call in routes
        if has_backend:
            report.checks.append(Check(f"Frontend calls {call}", "pass" if matched else "fail", "Backend route exists" if matched else "No matching backend route"))

    # 2. environment variable + CORS alignment
    if calls:
        env_file = by_path.get(".env.example")
        env_name = widgets.env_name()
        ok_env = bool(env_file and env_name in env_file.content)
        report.checks.append(Check("Frontend knows the API address", "pass" if ok_env else "fail", f"{env_name} is set in .env.example" if ok_env else f"{env_name} missing"))
    if has_backend:
        origin = {"nextjs": "http://localhost:3000", "react": "http://localhost:5173", "html": "http://localhost:8080"}[framework]
        be_env = by_path.get("backend/.env.example")
        if be_env:
            m = re.search(r"^CORS_ORIGINS=(.*)$", be_env.content, re.M)
            current = [o.strip() for o in (m.group(1) if m else "").split(",") if o.strip()]
            if origin not in current:
                current.append(origin)
                be_env.content = re.sub(r"^CORS_ORIGINS=.*$", "CORS_ORIGINS=" + ",".join(current), be_env.content, flags=re.M)
                report.actions.append(f"Added {origin} to the backend CORS_ORIGINS so the browser is allowed to call the API.")
            report.checks.append(Check("Backend allows the frontend origin (CORS)", "pass", f"{origin} is allowed"))
        if any(f.path == "backend/app/shop.py" for f in files):
            report.checks.append(Check("Razorpay payments", "info", "Runs in mock mode until RAZORPAY_KEY_ID and RAZORPAY_KEY_SECRET are set."))
        report.checks.append(Check("Backend ships its own end-to-end tests", "pass" if "backend/tests/test_e2e.py" in by_path else "warn", "backend/tests/test_e2e.py" if "backend/tests/test_e2e.py" in by_path else "No tests were generated for this framework"))
        report.checks.append(Check("Connected forms", "pass", "Contact, booking and newsletter forms submit to the API") if any(n.get("type") == "forms" for p in project.get("pages", []) for n in p.get("tree", [])) else Check("Connected forms", "info", "No forms on the site"))
    if framework == "html" and any(n.get("type") in widgets.WIDGET_TYPES for p in project.get("pages", []) for n in p.get("tree", [])):
        report.checks.append(Check("Interactive widgets", "warn", "HTML export cannot run the shop, chat or tracking widgets. Export as Next.js or React."))

    # 3. docs
    requirements = (project.get("settings") or {}).get("docs", {})
    for path, key in (("docs/REQUIREMENTS.md", "requirements"), ("docs/ACCEPTANCE.md", "acceptance")):
        if requirements.get(key):
            files.append(GenFile(path, requirements[key]))
            report.actions.append(f"Included {path} from the intake conversation.")
    readme = _full_readme(project, options, files, report, has_backend)
    files[:] = [f for f in files if f.path != "README.md"] + [GenFile("README.md", readme)]
    report.actions.append("Wrote a full-stack README with start-up steps for the frontend and backend.")
    files.append(GenFile("INTEGRATION_REPORT.md", render_report(project, report)))
    return files, report


ICON = {"pass": "PASS", "fail": "FAIL", "warn": "WARN", "info": "INFO"}


def render_report(project: dict, report: IntegrationReport) -> str:
    lines = [f"# Integration report — {project.get('name', 'Project')}", "", f"Overall: **{'OK' if report.ok else 'NEEDS ATTENTION'}**", "", "## Checks", ""]
    lines += [f"- `{ICON[c.status]}` **{c.name}** {('— ' + c.detail) if c.detail else ''}" for c in report.checks]
    if report.actions:
        lines += ["", "## What the integration agent did", ""] + [f"- {a}" for a in report.actions]
    if report.routes:
        lines += ["", "## Backend routes", ""] + [f"- `{r}`" for r in report.routes]
    return "\n".join(lines) + "\n"
