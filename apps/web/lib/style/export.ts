import { cssVarsFor, fontsOf } from "./engine";
import { fontsUrl } from "./fonts";
import type { StyleSpec, StyleTokens } from "./types";

const ren = (vars: Record<string, string>) =>
  Object.entries(vars)
    .filter(([k]) => !k.startsWith("--s-bg-l"))
    .map(([k, v]) => `  ${k.replace("--s-", "--vibe-")}: ${v};`)
    .join("\n");

export function toFontImport(spec: StyleSpec) {
  return `/* Google Fonts */\n@import url("${fontsUrl(fontsOf(spec))}");\n\n<!-- or in <head> -->\n<link rel="preconnect" href="https://fonts.googleapis.com">\n<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>\n<link rel="stylesheet" href="${fontsUrl(fontsOf(spec))}">`;
}

export function toComponentCss(spec: StyleSpec) {
  const glass = spec.card === "glass" || spec.glass;
  const btn =
    spec.button === "outline" ? "background: transparent; color: var(--vibe-primary); border: max(var(--vibe-bw), 1.5px) solid var(--vibe-primary);"
    : spec.button === "gradient" ? "background: var(--vibe-grad); color: var(--vibe-on-primary); border: 0;"
    : spec.button === "tonal" ? "background: var(--vibe-primary-c); color: var(--vibe-on-primary-c); border: 0;"
    : spec.button === "brutal" ? "background: var(--vibe-accent); color: var(--vibe-on-accent); border: 3px solid var(--vibe-text); box-shadow: var(--vibe-shadow-1);"
    : "background: var(--vibe-primary); color: var(--vibe-on-primary); border: 0;";
  return `/* Component styles — generated by VIBE Style Studio */
.btn {
  ${btn}
  border-radius: var(--vibe-r-btn);
  padding: var(--vibe-sp-3) var(--vibe-sp-5);
  font: 600 var(--vibe-base)/1 var(--vibe-font-b);
  transition: transform var(--vibe-dur) var(--vibe-ease), box-shadow var(--vibe-dur) var(--vibe-ease);
}
.btn:hover { transform: translateY(var(--vibe-lift)) scale(var(--vibe-scale)); }
.btn:focus-visible { outline: none; box-shadow: var(--vibe-focus); }

.card {
  background: ${glass ? "var(--vibe-glass-bg)" : spec.card === "flat" ? "transparent" : "var(--vibe-surface)"};
  ${glass ? "backdrop-filter: blur(var(--vibe-glass-blur));" : ""}
  border: var(--vibe-bw) solid var(--vibe-outline);
  border-radius: var(--vibe-r-card);
  box-shadow: ${spec.card === "elevated" || spec.card === "brutal" || spec.card === "soft" ? "var(--vibe-shadow-2)" : "none"};
  padding: var(--vibe-sp-5);
  transition: transform var(--vibe-dur) var(--vibe-ease), box-shadow var(--vibe-dur) var(--vibe-ease);
}
.card:hover { transform: translateY(var(--vibe-lift)); }

.input {
  background: var(--vibe-bg);
  color: var(--vibe-text);
  border: max(var(--vibe-bw), 1px) solid var(--vibe-outline);
  border-radius: var(--vibe-r-input);
  padding: var(--vibe-sp-3) var(--vibe-sp-4);
  font: var(--vibe-base) var(--vibe-font-b);
}
.input:focus { outline: none; box-shadow: var(--vibe-focus); border-color: var(--vibe-primary); }

h1, h2, h3 { font-family: var(--vibe-font-h); font-weight: var(--vibe-w-h); letter-spacing: var(--vibe-track-h); text-transform: var(--vibe-transform); line-height: var(--vibe-lh-h); }
body { background: var(--vibe-bg); color: var(--vibe-text); font: var(--vibe-base)/var(--vibe-lh) var(--vibe-font-b); }
img { filter: var(--vibe-img-filter); }

@media (prefers-reduced-motion: reduce) { * { transition: none !important; animation: none !important; } }`;
}

export function toCss(spec: StyleSpec, tokens: StyleTokens) {
  const light = cssVarsFor(spec, tokens, "light");
  const dark = cssVarsFor(spec, tokens, "dark");
  return `/* VIBE design system — ${spec.name} · fingerprint generated locally */
${toFontImport(spec).split("\n\n")[0]}

:root {
${ren(light)}
}

:root[data-theme="dark"] {
${ren(dark)}
}

${toComponentCss(spec)}
`;
}

