export function toJson(spec: StyleSpec, tokens: StyleTokens) {
  const { fix, locks, ...rest } = spec;
  return JSON.stringify({ format: "vibe-style@1", spec: { ...rest, fix }, tokens }, null, 2);
}

export function download(filename: string, content: string, type = "text/plain") {
  const blob = new Blob([content], { type });
  const a = document.createElement("a");
  a.href = URL.createObjectURL(blob);
  a.download = filename;
  a.click();
  setTimeout(() => URL.revokeObjectURL(a.href), 1000);
}

export function shareLink(spec: StyleSpec) {
  const { fix, locks, ...rest } = spec;
  const b64 = btoa(unescape(encodeURIComponent(JSON.stringify(rest))));
  return `${location.origin}${location.pathname}#style=${b64}`;
}

export function parseShared(hash: string): StyleSpec | null {
  const m = /style=([^&]+)/.exec(hash);
  if (!m) return null;
  try {
    const obj = JSON.parse(decodeURIComponent(escape(atob(m[1]))));
    return { ...obj, fix: { light: {}, dark: {} }, locks: {} } as StyleSpec;
  } catch {
    return null;
  }
}
